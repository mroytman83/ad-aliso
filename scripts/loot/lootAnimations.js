/**
 * @param {string} animId
 * @returns {string[]}
 */
export function getLootAnimLines(animId) {
    return LOOT_ANIMATIONS[animId]?.lines ?? LOOT_ANIMATIONS.abandoned_bag.lines;
}

/**
 * @param {string} animId
 */
export function getLootAnimMeta(animId) {
    return LOOT_ANIMATIONS[animId] ?? LOOT_ANIMATIONS.abandoned_bag;
}

/**
 * @param {string} animId
 * @returns {string}
 */
export function getLootAnimLabel(animId) {
    return LOOT_ANIMATIONS[animId]?.label ?? 'Loot';
}

/**
 * @param {number} worldSeed
 * @param {string} instanceId
 * @returns {string}
 */
export function pickLootAnimId(worldSeed, instanceId) {
    const rnd = mulberry32(stableHash32(`${worldSeed}|loot|anim|${instanceId}`));
    const idx = Math.floor(rnd() * LOOT_ANIM_IDS.length);
    return LOOT_ANIM_IDS[idx] ?? LOOT_ANIM_IDS[0];
}
